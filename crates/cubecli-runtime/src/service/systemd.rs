//! systemd user unit (Linux). Headless boxes need `loginctl enable-linger`
//! for the daemon to survive logout — surfaced in `daemon install` output.

use crate::error::{Result, RuntimeError};
use crate::service::{SYSTEMD_UNIT, ServiceSpec};

pub fn render(spec: &ServiceSpec) -> String {
    let exe = spec.exe.display();
    let out = spec.log_out.display();
    let err = spec.log_err.display();
    format!(
        r#"# generated by cubecli
[Unit]
Description=cubecli daemon (Minecraft server automation)
After=network-online.target

[Service]
ExecStart={exe} daemon run
Restart=on-failure
StandardOutput=append:{out}
StandardError=append:{err}
Environment=PATH=/usr/bin:/bin

[Install]
WantedBy=default.target
"#
    )
}

fn systemctl(args: &[&str]) -> Result<()> {
    let output = std::process::Command::new("systemctl")
        .arg("--user")
        .args(args)
        .output()
        .map_err(|e| RuntimeError::Other(format!("cannot run systemctl: {e}")))?;
    if !output.status.success() {
        return Err(RuntimeError::Other(format!(
            "systemctl --user {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    Ok(())
}

pub fn reload() -> Result<()> {
    let _ = systemctl(&["daemon-reload"]);
    systemctl(&["enable", "--now", SYSTEMD_UNIT])
}

pub fn unload() -> Result<()> {
    let _ = systemctl(&["disable", "--now", SYSTEMD_UNIT]);
    Ok(())
}
